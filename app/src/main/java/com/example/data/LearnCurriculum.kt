    fun wordsForModule(moduleId: Int): List<VocabWordItem> = when (moduleId) {
        1 -> module1Words
        5 -> module5Words
        else -> fallbackWordsForModule(moduleId)
    }

    fun allKnownWords(): List<VocabWordItem> =
        module1Words + module5Words + (1..12)
            .filter { it != 1 && it != 5 }
            .flatMap { fallbackWordsForModule(it) }

    fun wordById(id: String): VocabWordItem? = allKnownWords().firstOrNull { it.id == id }

